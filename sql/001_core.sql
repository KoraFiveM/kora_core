CREATE TABLE IF NOT EXISTS `players` (
  `id`            INT UNSIGNED     NOT NULL AUTO_INCREMENT,
  `citizenid`     VARCHAR(50)      NOT NULL,
  `license`       VARCHAR(60)      NOT NULL,
  `cid`           TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `name`          VARCHAR(255)     NOT NULL DEFAULT 'unknown',
  `money`         LONGTEXT         NOT NULL,
  `charinfo`      LONGTEXT         NOT NULL,
  `job`           LONGTEXT         NOT NULL,
  `gang`          LONGTEXT         NOT NULL,
  `position`      LONGTEXT         NOT NULL,
  `metadata`      LONGTEXT         NOT NULL,
  `inventory`     LONGTEXT                  DEFAULT NULL,
  `phone_number`  VARCHAR(20)               DEFAULT NULL,
  `created_at`    TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `last_updated`  TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted_at`    TIMESTAMP        NULL     DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_players_citizenid`   (`citizenid`),
  UNIQUE KEY `uk_players_license_cid` (`license`,`cid`),
  UNIQUE KEY `uk_players_phone`       (`phone_number`),
  KEY `idx_players_license_deleted`   (`license`,`deleted_at`),
  KEY `idx_players_last_updated`      (`last_updated`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
