-- Core.util smoke test -- the QBCore.Shared.* primitives + pathGet/pathSet.
local h = dofile('test/harness.lua')
local mocks = dofile('test/mocks.lua'); mocks.install()
dofile('config.lua')
dofile('modules/util/shared.lua')

h.test('round to places', function()
    h.assertEqual(Core.util.round(1.2345, 2), 1.23)
    h.assertEqual(Core.util.round(1.9), 2)
end)
h.test('trim', function() h.assertEqual(Core.util.trim('  hi  '), 'hi') end)
h.test('splitStr', function()
    local parts = Core.util.splitStr('a,b,c', ',')
    h.assertEqual(#parts, 3); h.assertEqual(parts[2], 'b')
end)
h.test('randomStr length + charset', function()
    local s = Core.util.randomStr(6)
    h.assertEqual(#s, 6)
    h.assertTrue(s:match('^[A-Z]+$') ~= nil, 'letters only')
end)
h.test('randomInt returns a digit STRING (legacy behaviour)', function()
    local s = Core.util.randomInt(4)
    h.assertEqual(type(s), 'string'); h.assertEqual(#s, 4)
    h.assertTrue(s:match('^%d+$') ~= nil)
end)
h.test('pathGet / pathSet nested', function()
    local t = {}
    local prev = Core.util.pathSet(t, { 'a', 'b', 'c' }, 5)
    h.assertTrue(prev == nil, 'no previous value')
    h.assertEqual(Core.util.pathGet(t, { 'a', 'b', 'c' }), 5)
    local prev2 = Core.util.pathSet(t, { 'a', 'b', 'c' }, 9)
    h.assertEqual(prev2, 5, 'returns previous value')
end)
h.test('deepClone is independent', function()
    local a = { x = { y = 1 } }
    local b = Core.util.deepClone(a)
    b.x.y = 2
    h.assertEqual(a.x.y, 1, 'original unchanged')
end)
h.report('util')
