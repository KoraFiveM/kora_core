CREATE TABLE IF NOT EXISTS `player_vehicles` (
  `id`             INT UNSIGNED     NOT NULL AUTO_INCREMENT,
  `plate`          VARCHAR(15)      NOT NULL,
  `model`          VARCHAR(60)      NOT NULL,
  `citizenid`      VARCHAR(50)               DEFAULT NULL,
  `job`            VARCHAR(50)               DEFAULT NULL,
  `state`          ENUM('out','garaged','impounded') NOT NULL DEFAULT 'garaged',
  `garage_id`      VARCHAR(50)               DEFAULT NULL,
  `fuel`           TINYINT UNSIGNED NOT NULL DEFAULT 100,
  `engine_health`  SMALLINT UNSIGNED NOT NULL DEFAULT 1000,
  `body_health`    SMALLINT UNSIGNED NOT NULL DEFAULT 1000,
  `mods`           LONGTEXT                  DEFAULT NULL,
  `last_position`  LONGTEXT                  DEFAULT NULL,
  `impound_fee`    INT UNSIGNED              DEFAULT NULL,
  `impound_lot`    VARCHAR(50)               DEFAULT NULL,
  `impounded_at`   TIMESTAMP        NULL     DEFAULT NULL,
  `created_at`     TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `last_updated`   TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted_at`     TIMESTAMP        NULL     DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_vehicles_plate` (`plate`),
  KEY `idx_vehicles_citizenid` (`citizenid`),
  KEY `idx_vehicles_job` (`job`),
  KEY `idx_vehicles_state` (`state`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
